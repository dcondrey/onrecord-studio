#!/usr/bin/env node
// Renders docs/METHODS.md: the analytical methods document followed by the eval-set scorecards
// the test suite wrote (src-tauri/tests/fixtures/*/scorecard.json). The methods text is the
// source of truth in docs/analysis_methods.md; this page adds the evidence that each documented
// method behaves as described on the hand-verified cases, so it can be published with a release.
//
//   node scripts/build-methods.mjs           # write docs/METHODS.md
//   node scripts/build-methods.mjs --check   # fail if docs/METHODS.md is stale

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const methodsPath = join(root, 'docs/analysis_methods.md');
const fixturesRoot = join(root, 'src-tauri/tests/fixtures');
const outputPath = join(root, 'docs/METHODS.md');

function scorecards() {
  if (!existsSync(fixturesRoot)) return [];
  return readdirSync(fixturesRoot)
    .map((name) => join(fixturesRoot, name))
    .filter((path) => statSync(path).isDirectory() && existsSync(join(path, 'scorecard.json')))
    .map((path) => JSON.parse(readFileSync(join(path, 'scorecard.json'), 'utf8')))
    .sort((a, b) => String(a.evalSet).localeCompare(String(b.evalSet)));
}

function cell(value) {
  return String(value ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function renderScorecard(card) {
  const lines = [];
  lines.push(`### Eval set \`${cell(card.evalSet)}\``);
  lines.push('');
  lines.push('| expected outcome | passed | total |');
  lines.push('|---|---|---|');
  for (const row of card.totals ?? []) {
    lines.push(`| ${cell(row.expected)} | ${cell(row.passed)} | ${cell(row.total)} |`);
  }
  lines.push('');
  lines.push('| case | sentence | expected | outcome | observed | passed |');
  lines.push('|---|---|---|---|---|---|');
  for (const row of card.cases ?? []) {
    lines.push(
      `| ${cell(row.id)} | ${cell(row.text)} | ${cell(row.expected)} | ${cell(row.outcome)} | ${cell(row.observed)} | ${row.passed ? 'yes' : 'no'} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}

const methods = readFileSync(methodsPath, 'utf8').trimEnd();
const cards = scorecards();
const sections = [
  '<!-- Generated by scripts/build-methods.mjs from docs/analysis_methods.md and the eval-set scorecards. Edit those, not this file. -->',
  '',
  methods,
  '',
  '---',
  '',
  '## Appendix: Eval-Set Scorecards',
  '',
  'Each scorecard is written by the test suite when it runs the named eval set (`cargo test --test detector_benchmark`). A case passes when the evaluator returns the outcome a person verified against the source rows. The sentences and the rows behind them live under `src-tauri/tests/fixtures/`.',
  '',
  cards.length === 0 ? '_No scorecard has been written yet. Run the detector benchmark tests._' : cards.map(renderScorecard).join('\n'),
  '',
];
const rendered = sections.join('\n');

if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== rendered) {
    console.error('docs/METHODS.md is stale: run `node scripts/build-methods.mjs`.');
    process.exit(1);
  }
  console.log('docs/METHODS.md is current.');
} else {
  writeFileSync(outputPath, rendered);
  console.log(`wrote docs/METHODS.md (${cards.length} scorecard${cards.length === 1 ? '' : 's'})`);
}
