import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import process from 'node:process';

const root = resolve(import.meta.dirname, '..');
const checkOnly = process.argv.includes('--check');
const generatedRoot = join(root, 'src/generated');

const registry = read('src-tauri/src/lib.rs');
const registrations = [...registry.matchAll(/commands::([a-z_]+)::([a-z_]+)/g)]
  .map((match) => ({ module: match[1], name: match[2] }));

const nativeCommands = registrations.map(({ module, name }) => {
  const source = read(`src-tauri/src/commands/${module}.rs`);
  const signature = source.match(new RegExp(`#\\[tauri::command\\]\\s*pub async fn ${name}\\s*\\(([\\s\\S]*?)\\)\\s*->\\s*Result<([\\s\\S]*?),\\s*AppError>`));
  if (!signature) throw new Error(`Could not parse Rust command signature ${module}::${name}.`);
  const args = splitTopLevel(signature[1]).map(parseField).filter((field) => !field.rustType.startsWith('State<'));
  return { name, args, result: rustTypeToTs(signature[2]) };
});

const nativeOutput = `${banner('Rust Tauri command signatures')}import type * as Types from '../types';

export type NoArgs = Record<string, never>;

export interface NativeCommandMap {
${nativeCommands.map((command) => `  ${command.name}: { args: ${command.args.length === 0 ? 'NoArgs' : `{ ${command.args.map((arg) => `${camel(arg.name)}${isOption(arg.rustType) ? '?' : ''}: ${rustTypeToTs(arg.rustType)}`).join('; ')} }`}; result: ${command.result} };`).join('\n')}
}
`;

const queue = read('src-tauri/src/ingestion/queue.rs');
const progressBody = blockAfter(queue, 'pub enum IngestionProgress');
const progressVariants = parseStructVariants(progressBody);
const telemetryOutput = `${banner('Rust IngestionProgress and IngestionTelemetryEnvelope')}import type * as Types from '../types';

export type IngestionTelemetryEvent =
${progressVariants.map((variant) => `  | { type: '${camel(variant.name)}'; payload: ${variant.fields.length === 0 ? 'Record<string, never>' : `{ ${variant.fields.map((field) => `${camel(field.name)}: ${rustTypeToTs(field.rustType)}`).join('; ')} }`} }`).join('\n')};

export type IngestionTelemetry = {
  protocolVersion: 1;
  sequence: string;
  emittedAt: string;
} & IngestionTelemetryEvent;
`;

const audit = read('src-tauri/src/types/audit.rs');
const verificationStates = parseUnitVariants(blockAfter(audit, 'pub enum VerificationState'));
const anomalyMarkers = parseUnitVariants(blockAfter(audit, 'pub enum TimelineAnomalyMarker'));
const auditOutput = `${banner('Rust VerificationState and TimelineAnomalyMarker')}export type VerificationState =
${verificationStates.map((value) => `  | '${value}'`).join('\n')};

export type TimelineAnomalyMarker =
${anomalyMarkers.map((value) => `  | '${screamingSnake(value)}'`).join('\n')};
`;

const analysis = read('src-tauri/src/types/analysis.rs');
const configBlock = blockAfter(analysis, 'pub struct AnalysisConfig');
const configFields = splitTopLevel(configBlock).map(parseField);
const analysisOutput = `${banner('Rust AnalysisConfig')}export interface AnalysisConfig {
${configFields.map((field) => `  ${field.name}?: ${rustTypeToTs(field.rustType).replaceAll('Types.', '')};`).join('\n')}
}
`;

emit('nativeCommands.ts', nativeOutput);
emit('ingestionTelemetry.ts', telemetryOutput);
emit('auditContracts.ts', auditOutput);
emit('analysisConfig.ts', analysisOutput);

if (!checkOnly) globalThis.console.log(`Generated ${nativeCommands.length} native commands, ${progressVariants.length} telemetry variants, ${verificationStates.length} verification states, and AnalysisConfig.`);

function emit(name, content) {
  const path = join(generatedRoot, name);
  if (checkOnly) {
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch { /* handled below */ }
    if (current !== content) throw new Error(`${name} is stale. Run npm run generate:contracts.`);
    return;
  }
  mkdirSync(generatedRoot, { recursive: true });
  writeFileSync(path, content);
}

function read(path) { return readFileSync(join(root, path), 'utf8'); }
function banner(source) { return `// @generated by scripts/generate-contracts.mjs from ${source}. Do not edit.\n\n`; }
function isOption(type) { return type.trim().startsWith('Option<'); }

function parseField(value) {
  const cleaned = value.replace(/\/\/\/[^\n]*\n/g, '').replace(/#\[[^\]]+\]/g, '').trim().replace(/,$/, '');
  const colon = cleaned.indexOf(':');
  if (colon < 1) throw new Error(`Could not parse Rust field: ${cleaned}`);
  return { name: cleaned.slice(0, colon).trim().replace(/^pub\s+/, ''), rustType: cleaned.slice(colon + 1).trim() };
}

function rustTypeToTs(value) {
  const type = value.trim().replace(/^&(?:'\w+\s+)?/, '');
  const option = unwrap(type, 'Option');
  if (option !== null) return `${rustTypeToTs(option)} | null`;
  const vector = unwrap(type, 'Vec');
  if (vector !== null) return `${rustTypeToTs(vector)}[]`;
  if (['String', 'str'].includes(type)) return 'string';
  if (type === 'bool') return 'boolean';
  if (type === '()') return 'null';
  if (/^(?:u|i)(?:8|16|32|64|128|size)$/.test(type) || /^(?:f32|f64)$/.test(type)) return 'number';
  const name = type.split('::').at(-1).replace(/[>,].*$/, '').trim();
  const aliases = { UnredactorForensicReport: 'RedactionIntegrityReport' };
  return `Types.${aliases[name] ?? name}`;
}

function unwrap(type, wrapper) {
  const prefix = `${wrapper}<`;
  return type.startsWith(prefix) && type.endsWith('>') ? type.slice(prefix.length, -1).trim() : null;
}

function splitTopLevel(value) {
  const parts = [];
  let start = 0;
  let depth = 0;
  for (let index = 0; index < value.length; index += 1) {
    const character = value[index];
    if ('<({['.includes(character)) depth += 1;
    else if ('>)}]'.includes(character)) depth -= 1;
    else if (character === ',' && depth === 0) {
      const part = value.slice(start, index).trim();
      if (part) parts.push(part);
      start = index + 1;
    }
  }
  const tail = value.slice(start).trim();
  if (tail) parts.push(tail);
  return parts;
}

function blockAfter(source, anchor) {
  const anchorIndex = source.indexOf(anchor);
  if (anchorIndex < 0) throw new Error(`Could not find ${anchor}.`);
  const open = source.indexOf('{', anchorIndex);
  let depth = 0;
  for (let index = open; index < source.length; index += 1) {
    if (source[index] === '{') depth += 1;
    else if (source[index] === '}' && --depth === 0) return source.slice(open + 1, index);
  }
  throw new Error(`Could not close ${anchor}.`);
}

function parseStructVariants(body) {
  const variants = [];
  let cursor = 0;
  while (cursor < body.length) {
    const match = body.slice(cursor).match(/(?:^|\n)\s*(?:\/\/\/[^\n]*\n\s*)*([A-Z][A-Za-z0-9]*)\s*\{/);
    if (!match) break;
    const name = match[1];
    const open = cursor + match.index + match[0].lastIndexOf('{');
    let depth = 0;
    let close = open;
    for (; close < body.length; close += 1) {
      if (body[close] === '{') depth += 1;
      else if (body[close] === '}' && --depth === 0) break;
    }
    const fields = splitTopLevel(body.slice(open + 1, close)).map(parseField);
    variants.push({ name, fields });
    cursor = close + 1;
  }
  return variants;
}

function parseUnitVariants(body) {
  return body
    .replace(/\/\/\/[^\n]*/g, '')
    .split(',')
    .map((value) => value.trim())
    .filter((value) => /^[A-Z][A-Za-z0-9]*$/.test(value));
}

function camel(value) { return value.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase()).replace(/^([A-Z])/, (letter) => letter.toLowerCase()); }
function screamingSnake(value) { return value.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase(); }
